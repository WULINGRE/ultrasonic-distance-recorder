const uint16_t Chinese16_Count =
    (uint16_t)(sizeof(Chinese16_Table) / sizeof(Chinese16_Table[0]));

const uint8_t *Font_GetASCII8x16(char ch)
{
    uint8_t c = (uint8_t)ch;

    if((c < FONT_ASCII_FIRST) || (c > FONT_ASCII_LAST))
    {
        c = (uint8_t)'?';
    }

    return ASCII8x16[c - FONT_ASCII_FIRST];
}

const uint8_t *Font_GetChinese16(uint16_t unicode)
{
    uint16_t i;

    for(i = 0U; i < Chinese16_Count; i++)
    {
        if(Chinese16_Table[i].unicode == unicode)
        {
            return Chinese16_Table[i].data;
        }
    }

    return 0;
}

uint8_t Font_HasChinese16(uint16_t unicode)
{
    return (Font_GetChinese16(unicode) != 0) ? 1U : 0U;
}
